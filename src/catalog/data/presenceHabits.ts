type HabitInput = {
  id: string
  name: string
  measures: string
  howMeasured: string
  methods?: Metric['methods']
  unit: string
  min: number | null
  max: number | null
  scaleDescription: string
  summary: string
  lo: number | null
  hi: number | null
  rationale: string
  confidence: 'high' | 'medium' | 'low'
  caveat?: string
  evidence: Metric['evidence']
  evidenceNote: string
  communityClaim?: string
  sourceIds: string[]
  target: string
  period: 'day' | 'week'
  weightRationale?: string
  medicalFlag?: string
  phase?: Metric['phase']
  refusal?: string[]
}

function habit(h: HabitInput): Metric {
  return {
    id: h.id,
    category: 'habits',
    name: h.name,
    measures: h.measures,
    howMeasured: h.howMeasured,
    methods: h.methods ?? ['HABIT_LOG'],
    scale: { unit: h.unit, min: h.min, max: h.max, description: h.scaleDescription, higherIs: 'target_range' },
    ideal: {
      summary: h.summary,
      male: { lo: h.lo, hi: h.hi },
      rationale: h.rationale,
      confidenceInIdeal: h.confidence,
      ...(h.caveat ? { populationCaveat: h.caveat } : {}),
    },
    scoring: { kind: 'none', reason: 'habit' },
    changeability: 'CHANGEABLE',
    weight: 0,
    weightRationale:
      h.weightRationale ??
      'Habits are causes of appearance, not appearance. Scoring them would count the same effect twice, so they feed the Adherence Index instead.',
    evidence: h.evidence,
    evidenceNote: h.evidenceNote,
    ...(h.communityClaim ? { communityClaim: h.communityClaim } : {}),
    sourceIds: h.sourceIds,
    drivers: [],
    captureRequirements: ['habit_log'],
    refusalConditions: h.refusal ?? [],
    ...(h.medicalFlag ? { medicalFlag: h.medicalFlag } : {}),
    phase: h.phase ?? 'M3',
    adherence: { target: h.target, unit: h.unit, targetLo: h.lo, targetHi: h.hi, period: h.period },
  }
}

